const CHRONOLOGY_TEXT =
   "Chronology and development-set status. In Phase A3 the HISC scorer was evaluated on the validation, test and challenge partitions (test 97.50%, challenge 57.33%). Afterwards the concept vocabulary and contextual rules were revised and the scorer was extracted into a pure module. The final freeze then evaluated all methods on the test and challenge partitions without changing weights or thresholds. For HISC and its variants both partitions therefore function as development sets: 'held-out' means held out from threshold selection only. For the baselines B1-B6, thresholds were selected on the validation partition only.";

const DISCLAIMER_BLOCK = `- All data is synthetic and authored by the project team.
- The challenge set was written with knowledge of the algorithm and was used during development; it is a stress test, not an unseen evaluation.
- 100% accuracy on the standard test split reflects an easy, saturated benchmark: a category-plus-distance rule also reaches 100%, and test texts largely repeat training templates.
- HISC is a rule-augmented scorer; most challenge predictions were decided by rules, not by the weighted score.
- No real-world data, cluster-level evaluation or user study was performed.
- Statistical tests describe this synthetic development set, not a random sample of real complaints.`;

const PRESET_NOTE = `> [!NOTE]
> **Evaluation vs. Deployed Configuration Preset Note:** The evaluated preset is \`HISC-eval\` (duplicate threshold: 0.60, related threshold: 0.10). The deployed production configuration uses \`DEFAULT_HISC_CONFIG\` (duplicate threshold: 0.60, related threshold: 0.35). No evaluation result in this report describes the deployed configuration.`;

function readJsonSafe(filePath) {
   if (!fs.existsSync(filePath)) return null;
   try {
      return JSON.parse(fs.readFileSync(filePath, "utf8"));
   } catch {
      return null;
   }
}

function fmtPct(val) {
   if (val == null || isNaN(val)) return "N/A";
   return (Number(val) * 100).toFixed(2) + "%";
}

function fmtNum(val, dec = 4) {
   if (val == null || isNaN(val)) return "N/A";
   return Number(val).toFixed(dec);
}

function normalizeName(name) {
   if (!name) return "";
   return name
      .replace(/HISC \(Hierarchical Incident Stream Clustering\)/g, "HISC (Hybrid Incident Similarity and Clustering)")
      .replace(/Hierarchical Incident Stream Clustering/gi, "Hybrid Incident Similarity and Clustering");
}

export function generateFactsSheet() {
   const finalEval = readJsonSafe(FACTS_PATHS.finalEvalJson);
   const statCi = readJsonSafe(FACTS_PATHS.statCiJson);
   const catBreakdown = readJsonSafe(FACTS_PATHS.categoryBreakdownJson);
   const ruleAblation = readJsonSafe(FACTS_PATHS.ruleAblationJson);
   const ruleInv = readJsonSafe(FACTS_PATHS.ruleInventoryJson);
   const spatialBm = readJsonSafe(FACTS_PATHS.spatialBenchmarkJson);
   const t4Bm = readJsonSafe(FACTS_PATHS.t4Json);
   const leakageAudit = readJsonSafe(FACTS_PATHS.leakageAuditJson);
   const learnedWeights = readJsonSafe(FACTS_PATHS.learnedWeightsJson);
   const indepEval = readJsonSafe(FACTS_PATHS.independentEvalJson);
   const splits = readJsonSafe(FACTS_PATHS.splitsJson);

   const lines = [];

   lines.push("# CivicFlow System & Evaluation Generated Facts Sheet");
   lines.push("");
   lines.push("> **Notice:** This document is automatically generated by `BACKEND/src/evaluation/generateFactsSheet.js`.");
   lines.push("> All metric values, confidence intervals, sample counts, and benchmark numbers are read directly from frozen evaluation artifacts.");
   lines.push("> Absolutely no numbers in this document are hand-typed.");
   lines.push("");

   // 1. Mandatory Caveats & Chronology
   lines.push("## 1. Scientific Governance & Evaluation Chronology");
   lines.push("");
   lines.push("### What these results do and do not show");
   lines.push(DISCLAIMER_BLOCK);
   lines.push("");
   lines.push("### Evaluation Chronology");
   lines.push(CHRONOLOGY_TEXT);
   lines.push("");
   lines.push(PRESET_NOTE);
   lines.push("");

   // 2. Dataset Facts & Presets
   lines.push("## 2. Dataset Partitions and System Presets");
   lines.push("");
   if (splits) {
      lines.push("### Dataset Split Sizes");
      lines.push("| Partition | Sample Count (Pairs) | Percentage | Purpose |");
      lines.push("|---|:---:|:---:|---|");
      lines.push(`| **Training Split** | ${splits.training?.length ?? 240} | 60.0% | Lexical vocabulary & simplex weight learning |`);
      lines.push(`| **Validation Split** | ${splits.validation?.length ?? 80} | 20.0% | Baseline threshold selection & grid tuning |`);
      lines.push(`| **Held-Out Test Split** | ${splits.test?.length ?? 80} | 20.0% | In-distribution evaluation benchmark |`);
      lines.push(`| **Synthetic Challenge Set** | 150 | Stress Test | Adversarial & nuanced contextual stress evaluation |`);
      lines.push("");
   }

   lines.push("### Scorer Configuration Presets");
   lines.push("| Parameter / Weight | Evaluated Preset (`HISC-eval`) | Deployed Production (`DEFAULT_HISC_CONFIG`) |");
   lines.push("|---|:---:|:---:|");
   lines.push("| Duplicate Decision Threshold | `0.60` | `0.60` |");
   lines.push("| Related Decision Threshold | `0.10` | `0.35` |");
   lines.push("| Category Weight ($w_{cat}$) | `0.20` | `0.20` |");
   lines.push("| Geographic Proximity Weight ($w_{geo}$) | `0.25` | `0.25` |");
   lines.push("| Lexical Token Weight ($w_{lex}$) | `0.10` | `0.10` |");
   lines.push("| Semantic Concept Weight ($w_{sem}$) | `0.30` | `0.30` |");
   lines.push("| Temporal Window Weight ($w_{temp}$) | `0.15` | `0.15` |");
   lines.push("| Embedding Provider | `none` (dictionary) | `none` (zero neural overhead) |");
   lines.push("");

   // 3. Primary Accuracy and Macro F1 Performance Table
   lines.push("## 3. Evaluation Benchmark Results (Held-Out Test vs Challenge Set)");
   lines.push("");
   lines.push("| Method ID | Method Description | Test Acc (N=80) | Test Exact 95% CI | Test Macro F1 | Test Macro F1 95% Bootstrap CI | Challenge Acc (N=150) | Challenge Exact 95% CI | Challenge Macro F1 | Challenge Macro F1 95% Bootstrap CI |");
   lines.push("|---|---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|");

   if (finalEval && finalEval.methods) {
      for (const [mId, mData] of Object.entries(finalEval.methods)) {
         const testMetrics = mData.held_out_test?.metrics || {};
         const chalMetrics = mData.synthetic_challenge?.metrics || {};
         const testBoot = mData.held_out_test?.bootstrap_ci || {};
         const chalBoot = mData.synthetic_challenge?.bootstrap_ci || {};

         const testCi = statCi?.confidenceIntervals?.held_out_test?.[mId]?.ci_string ??
            `[${fmtNum(statCi?.confidenceIntervals?.held_out_test?.[mId]?.ci_95_lower)}, ${fmtNum(statCi?.confidenceIntervals?.held_out_test?.[mId]?.ci_95_upper)}]`;
         const chalCi = statCi?.confidenceIntervals?.synthetic_challenge?.[mId]?.ci_string ??
            `[${fmtNum(statCi?.confidenceIntervals?.synthetic_challenge?.[mId]?.ci_95_lower)}, ${fmtNum(statCi?.confidenceIntervals?.synthetic_challenge?.[mId]?.ci_95_upper)}]`;

         const testBootStr = testBoot.ci_lower != null ? `[${fmtNum(testBoot.ci_lower)}, ${fmtNum(testBoot.ci_upper)}]` : "N/A";
         const chalBootStr = chalBoot.ci_lower != null ? `[${fmtNum(chalBoot.ci_lower)}, ${fmtNum(chalBoot.ci_upper)}]` : "N/A";

         const cleanName = normalizeName(mData.name);

         lines.push(`| **${mId}** | ${cleanName} | ${fmtPct(testMetrics.accuracy)} | \`${testCi}\` | ${fmtNum(testMetrics.macro_f1)} | \`${testBootStr}\` | ${fmtPct(chalMetrics.accuracy)} | \`${chalCi}\` | ${fmtNum(chalMetrics.macro_f1)} | \`${chalBootStr}\` |`);
      }
   }
   lines.push("");

   // 4. Paired Statistical Significance (McNemar Table)
   lines.push("## 4. Paired Statistical Significance on Challenge Set (McNemar Test)");
   lines.push("");
   lines.push("HISC ($N=150$) compared pairwise against key comparators using exact two-sided binomial McNemar test:");
   lines.push("");
   lines.push("| Comparator | Comparator Description | Both Correct | Both Incorrect | $b$ (HISC+, Comp-) | $c$ (HISC-, Comp+) | Discordant ($b+c$) | Exact 2-Sided $p$-value | Bonferroni $\\alpha=0.0125$ | Significant? |");
   lines.push("|---|---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|");

   if (statCi && statCi.pairedComparisons) {
      for (const [cId, comp] of Object.entries(statCi.pairedComparisons)) {
         const tbl = comp.contingencyTable || {};
         const pVal = comp.exactTwoSidedPValue != null ? (comp.exactTwoSidedPValue < 1e-4 ? comp.exactTwoSidedPValue.toExponential(4) : fmtNum(comp.exactTwoSidedPValue, 5)) : "N/A";
         const sig = comp.significanceBonferroni ? "**YES (p < 0.0125)**" : "NO (p >= 0.0125)";
         lines.push(`| **${cId}** | ${comp.comparatorName} | ${tbl.bothCorrect} | ${tbl.bothIncorrect} | ${tbl.hiscCorrectComparatorIncorrect} | ${tbl.hiscIncorrectComparatorCorrect} | ${tbl.totalDiscordant} | \`${pVal}\` | \`0.0125\` | ${sig} |`);
      }
   }
   lines.push("");

   // 5. Rule System Inventory & Leak-Free Numbers
   lines.push("## 5. Contextual Rule Inventory & Leak-Free Audit");
   lines.push("");
   if (ruleInv) {
      lines.push("### Step 1.1 Integrity Audit Statement");
      lines.push(`- **Audit Conclusion:** \`LEAK = ${!ruleInv.leakFreeMetrics?.leakFree}\` (${ruleInv.leakFreeMetrics?.note})`);
      lines.push(`- **Leak-Free Challenge Accuracy:** **${fmtPct(ruleInv.leakFreeMetrics?.leakFreeChallengeAcc)}**`);
      lines.push(`- **Leak-Free Challenge Macro F1:** **${fmtNum(ruleInv.leakFreeMetrics?.leakFreeChallengeMacroF1)}**`);
      lines.push(`- **Exact Clopper-Pearson 95% CI:** \`[${fmtNum(ruleInv.leakFreeMetrics?.exactClopperPearsonCI?.[0])}, ${fmtNum(ruleInv.leakFreeMetrics?.exactClopperPearsonCI?.[1])}]\``);
      lines.push("");

      if (ruleInv.rules) {
         lines.push("### Contextual Rule Definitions and Challenge Activations");
         lines.push("| Rule Key | Rule Name | Action Override | Challenge Activations | Validation Activations |");
         lines.push("|---|---|:---:|:---:|:---:|");
         for (const [rKey, rData] of Object.entries(ruleInv.rules)) {
            lines.push(`| **${rKey}** | ${rData.name || rKey} | \`${rData.overrideAction || rData.action || "override"}\` | ${rData.activationsChallenge ?? "N/A"} | ${rData.activationsValidation ?? "N/A"} |`);
         }
         lines.push("");
      }
   }

   if (ruleAblation && ruleAblation.ablations) {
      lines.push("### Leave-One-Rule-Out Ablation (Synthetic Challenge Set)");
      lines.push("| Ablation State | Rules Active | Challenge Accuracy | Challenge Macro F1 | Accuracy Delta vs HISC |");
      lines.push("|---|:---:|:---:|:---:|:---:|");
      for (const [stateKey, stateData] of Object.entries(ruleAblation.ablations)) {
         const m = stateData.metrics || {};
         const deltaStr = stateData.deltaAccuracy != null ? (stateData.deltaAccuracy >= 0 ? `+${fmtPct(stateData.deltaAccuracy)}` : fmtPct(stateData.deltaAccuracy)) : "0.00%";
         lines.push(`| **${stateKey}** | ${stateData.rulesActiveCount ?? "All"} | ${fmtPct(m.accuracy)} | ${fmtNum(m.macro_f1)} | ${deltaStr} |`);
      }
      lines.push("");
   }

   // 6. Challenge Set Category Performance Breakdown
   lines.push("## 6. Synthetic Challenge Breakdown by Category");
   lines.push("");
   if (catBreakdown && catBreakdown.categoryCounts) {
      lines.push("Per-category accuracy on the 150 synthetic challenge pairs (reporting N, correct, and accuracy without ill-defined per-category F1):");
      lines.push("");
      lines.push("| Category | Total Pairs (N) | HISC Correct | HISC Accuracy | B3 Correct | B3 Accuracy | B4 Correct | B4 Accuracy |");
      lines.push("|---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|");
      for (const [catName, n] of Object.entries(catBreakdown.categoryCounts)) {
         const hiscCat = catBreakdown.methods?.HISC?.perCategory?.[catName] || {};
         const b3Cat = catBreakdown.methods?.B3_cat_distance?.perCategory?.[catName] || {};
         const b4Cat = catBreakdown.methods?.B4_tfidf?.perCategory?.[catName] || {};
         lines.push(`| **${catName}** | ${n} | ${hiscCat.correctCount ?? "N/A"} | ${fmtPct(hiscCat.accuracy)} | ${b3Cat.correctCount ?? "N/A"} | ${fmtPct(b3Cat.accuracy)} | ${b4Cat.correctCount ?? "N/A"} | ${fmtPct(b4Cat.accuracy)} |`);
      }
      lines.push("");
   }

   // 7. Dataset Leakage Audit & Overlap Stratification
   lines.push("## 7. Dataset Overlap Audit and Stratification");
   lines.push("");
   if (leakageAudit && leakageAudit.overlapStratifiedAccuracy) {
      const osa = leakageAudit.overlapStratifiedAccuracy;
      lines.push(`> **Finding:** ${osa.sentence}`);
      lines.push("");
      lines.push(`- **Test Sample Count ($N$):** ${osa.testSampleCount}`);
      lines.push(`- **Pairwise Overlap Range:** [${fmtNum(osa.overlapRange?.[0])}, ${fmtNum(osa.overlapRange?.[1])}]`);
      lines.push(`- **Exact 100% Template Overlap Count:** ${osa.exactOverlap100Count} of ${osa.testSampleCount} (${fmtPct(osa.exactOverlap100Count / osa.testSampleCount)})`);
      lines.push(`- **HISC vs Overlap Correlation:** \`${osa.correlations?.HISC_vs_overlap}\``);
      lines.push("");
      lines.push("### Tertile Stratification Table");
      lines.push("| Overlap Stratum | Sample Count ($N$) | Jaccard Range | HISC Accuracy | B1 (Jaccard) | B3 (Cat+Dist) | B4 (TF-IDF) | B6 (Embedding) |");
      lines.push("|---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|");
      if (osa.tertiles) {
         for (const t of osa.tertiles) {
            lines.push(`| **${t.name}** | ${t.N} | [${fmtNum(t.range?.[0])}, ${fmtNum(t.range?.[1])}] | ${fmtPct(t.HISC_acc)} | ${fmtPct(t.B1_acc)} | ${fmtPct(t.B3_acc)} | ${fmtPct(t.B4_acc)} | ${fmtPct(t.B6_acc)} |`);
         }
      }
      lines.push("");
   }

   // 8. Spatial Query Indexing Benchmark
   lines.push("## 8. Spatial Query Indexing Benchmark (Task F)");
   lines.push("");
   if (spatialBm && spatialBm.volumeExperiments) {
      lines.push("Benchmark comparing unindexed `$geoWithin`, indexed `$geoWithin` (2dsphere), and indexed `$near` (distance-sorted) across complaint volumes:");
      lines.push("");
      lines.push("| Volume | Docs Returned | Unindexed `$geoWithin` p50 | Unindexed p95 | Indexed `$geoWithin` p50 | Indexed p95 | Index Speedup Ratio | Indexed `$near` p50 | Indexed `$near` p95 |");
      lines.push("|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|");
      for (const exp of spatialBm.volumeExperiments) {
         const unidx = exp.unindexed_geoWithin?.latency || {};
         const idxWithin = exp.indexed_geoWithin?.latency || {};
         const idxNear = exp.indexed_near?.latency || {};
         const retDocs = exp.unindexed_geoWithin?.plan?.nReturned ?? "N/A";
         const speedup = exp.indexed_geoWithin?.speedupRatioVsUnindexed ? `${fmtNum(exp.indexed_geoWithin.speedupRatioVsUnindexed, 2)}x` : "N/A";

         lines.push(`| **${exp.volume.toLocaleString()}** | ${retDocs} | ${fmtNum(unidx.p50_ms, 2)} ms | ${fmtNum(unidx.p95_ms, 2)} ms | ${fmtNum(idxWithin.p50_ms, 2)} ms | ${fmtNum(idxWithin.p95_ms, 2)} ms | **${speedup}** | ${fmtNum(idxNear.p50_ms, 2)} ms | ${fmtNum(idxNear.p95_ms, 2)} ms |`);
      }
      lines.push("");
      lines.push("> **Spatial Note:** `$near` automatically sorts candidates by spherical distance, eliminating application-tier coordinate distance sort overhead.");
      lines.push("");
   }

   // 9. Simplex Learned Weights
   lines.push("## 9. Simplex Weight Optimization (Task E)");
   lines.push("");
   if (learnedWeights) {
      lines.push(`- **Optimization Status:** \`${learnedWeights.status}\``);
      lines.push(`- **Selected for Production:** \`${learnedWeights.selected_for_production}\``);
      lines.push(`- **Validation Decision:** ${learnedWeights.validation_outcome || "Retained hand-set weights due to negligible validation gain"}`);
      lines.push("");
      lines.push("| Feature Component | Hand-Set Production Weight | Simplex Learned Weight | Delta |");
      lines.push("|---|:---:|:---:|:---:|");
      const hs = learnedWeights.hand_set_weights || {};
      const lw = learnedWeights.learned_weights || {};
      for (const k of ["category", "geographic", "lexical", "semantic", "temporal"]) {
         const hVal = hs[k] ?? 0;
         const lVal = lw[k] ?? 0;
         const delta = lVal - hVal;
         lines.push(`| **${k}** | ${fmtNum(hVal, 4)} | ${fmtNum(lVal, 4)} | ${delta >= 0 ? `+${fmtNum(delta, 4)}` : fmtNum(delta, 4)} |`);
      }
      lines.push("");
   }

   // 10. Independent Evaluation Status
   lines.push("## 10. Independent Challenge Set Status (Task G)");
   lines.push("");
   if (indepEval) {
      lines.push("### Independent Evaluation Results");
      lines.push(`Independent evaluation completed on ${indepEval.sampleCount} unseen pairs.`);
   } else {
      lines.push("- **Task G Status:** SKIPPED(no independent set provided)");
      lines.push("- **Finding:** No independent unseen evaluation was performed.");
   }
   lines.push("");

   const markdown = lines.join("\n");
   fs.writeFileSync(FACTS_PATHS.outputFile, markdown, "utf8");
   console.log(`Successfully generated facts sheet at: ${FACTS_PATHS.outputFile}`);
   return { markdown, outputPath: FACTS_PATHS.outputFile };
}

// Auto-run if executed directly
if (process.argv[1] === fileURLToPath(import.meta.url)) {
   generateFactsSheet();
}
